        {
            /*
             * TIPOS DE VARIABLES
             *
             * String: Cadena de caracteres, letras, números, etc.
             *
             * Int: Cuando queremos guardar valores numéricos enteros con signo,
             * en el rango de -2,147,483,648 hasta 2,147,483,647.
             *
             * Long: Guarda valores numéricos enteros realmente grandes,
             * con un rango desde -9,223,372,036,854,775,808
             * hasta 9,223,372,036,854,775,807.
             *
             * Short: Guarda valores numéricos enteros, pero su rango es menor
             * y varía desde -32,768 hasta 32,767.
             *
             * Byte: Puede guardar un byte de información.
             * Esto equivale a un valor entero positivo entre 0 y 255.
             *
             * Decimal: Este tipo puede guardar un valor numérico con decimales.
             * Es utilizado cuando necesitamos alta precisión en valores
             * decimales, por ejemplo, para cantidades monetarias.
             *
             * Float: Otro tipo muy utilizado para guardar valores numéricos
             * con decimales. Tiene una precisión menor que decimal.
             *
             * Bool: Es una variable booleana, es decir, que solamente puede
             * guardar los valores verdadero o falso (true o false)
             * en términos de C#.
             */
        }
    }
